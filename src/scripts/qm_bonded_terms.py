"""Record QM-fitted bonds and angles for lookup (``src/opls_ff_gen/qm_bonded.py``).

Collects every bond and angle with rule ``qm-fit`` from the molecule
directories of batch runs (``src/scripts/run_batch_opls2020.py``; each directory's
``*.topology.json`` and ``*.assigned.sdf``, same atom order), merges them into
the provenance record (``--record``; a molecule seen again replaces its earlier
entry) and writes the lookup file (``--par``) from the whole record:

- bonds keyed by their classes, angles by classes and small-ring context
  (``qm_bonded.angle_ring_context``);
- per molecule, symmetry copies (and any repeats) of one key are averaged
  first, so every molecule counts once; the value is the mean over molecules,
  with the count and the spread (max - min) over molecules in the comment.

    python src/scripts/qm_bonded_terms.py --batch DIR [DIR ...] \\
        [--record src/opls_ff_gen/data/qm_bonded_terms.json] \\
        [--par src/opls_ff_gen/data/qm_bonded_terms.par]

Terms already taken from the lookup file (rule ``qm-table``) are not recorded
again; to add new chemistry, run the batch with the current file and record it.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from rdkit import Chem  # noqa: E402

from opls_ff_gen.qm_bonded import (  # noqa: E402
    DEFAULT_QM_BONDED, angle_key, angle_ring_context, bond_key)
from opls_ff_gen.qm_fit import RULE_QM_FIT  # noqa: E402

DEFAULT_RECORD = DEFAULT_QM_BONDED.with_suffix(".json")


def _collect(directory: Path) -> dict | None:
    topologies = list(directory.glob("*.topology.json"))
    sdfs = list(directory.glob("*.assigned.sdf"))
    if len(topologies) != 1 or len(sdfs) != 1:
        return None
    topology = json.loads(topologies[0].read_text())
    bonds = [b for b in topology["bonds"] if b["rule"] == RULE_QM_FIT]
    angles = [a for a in topology["angles"] if a["rule"] == RULE_QM_FIT]
    if not bonds and not angles:
        return None
    molecule = Chem.MolFromMolFile(str(sdfs[0]), removeHs=False, sanitize=True)
    if molecule.GetNumAtoms() != len(topology["atom_types"]):
        raise ValueError(f"{sdfs[0]}: atom count differs from {topologies[0]}")
    for b in bonds:
        if molecule.GetBondBetweenAtoms(*(i - 1 for i in b["atoms"])) is None:
            raise ValueError(f"{sdfs[0]}: atoms {b['atoms']} are not bonded")
    return {
        "method": topology["qm_method"],
        "smiles": Chem.MolToSmiles(Chem.RemoveHs(molecule)),
        "bonds": [{"classes": list(bond_key(b["classes"])),
                   "b0_nm": b["length_nm"], "k_kj_mol_nm2": b["force_constant_kj_mol_nm2"]}
                  for b in bonds],
        "angles": [{"classes": list(angle_key(a["classes"], "")[:3]),
                    "context": angle_ring_context(molecule, *(i - 1 for i in a["atoms"])),
                    "theta0_deg": a["angle_deg"], "k_kj_mol_rad2": a["force_constant_kj_mol_rad2"]}
                   for a in angles],
    }


def _mean(values):
    return sum(values) / len(values)


def _write_par(path: Path, record: dict) -> int:
    per_key = defaultdict(dict)  # key -> molecule -> [(value, k)]
    for name, entry in record["molecules"].items():
        for b in entry["bonds"]:
            per_key[("bond", *b["classes"])].setdefault(name, []).append(
                (b["b0_nm"], b["k_kj_mol_nm2"]))
        for a in entry["angles"]:
            per_key[("angle", *a["classes"], a["context"])].setdefault(name, []).append(
                (a["theta0_deg"], a["k_kj_mol_rad2"]))
    methods = sorted({e["method"] for e in record["molecules"].values()})
    lines = [
        "# Bonds and angles recorded from on-the-fly QM fits (src/opls_ff_gen/qm_fit.py:",
        "# QM-optimized geometry, modified Seminario force constants), for terms the",
        "# OPLS/2020 tables lack. Supplementary (not part of the ACS SI); read by",
        "# src/opls_ff_gen/qm_bonded.py after the OPLS/2020 lookup, without the run-time QM fit.",
        f"# Generated by src/scripts/qm_bonded_terms.py on {date.today().isoformat()} from "
        f"{len(record['molecules'])} molecules",
        "# (provenance: qm_bonded_terms.json). QM: " + "; ".join(methods),
        "# Mean over molecules (symmetry copies within a molecule averaged first);",
        "# the comment gives the molecule count, the spread (max - min) and molecules.",
        "# bond  I J        b0 (nm)   k (kJ/mol/nm^2)",
        "# angle I J K ctx  theta0 (deg)   k (kJ/mol/rad^2); ctx: inN = angle in a ring",
        "#   of N <= 5 atoms, exoN = only the centre in such a ring, - = neither",
        "",
    ]
    for key in sorted(per_key, key=lambda k: (k[0] != "bond", k[1:])):
        molecules = per_key[key]
        values = [_mean([v for v, _ in m]) for m in molecules.values()]
        forces = [_mean([k for _, k in m]) for m in molecules.values()]
        names = sorted(molecules)
        comment = (f"; {len(names)} molecule{'s' if len(names) > 1 else ''}"
                   + (f", spread {max(values) - min(values):.{4 if key[0] == 'bond' else 1}f}"
                      f" / {max(forces) - min(forces):.0f}" if len(names) > 1 else "")
                   + f"; {' '.join(names[:4])}{' ...' if len(names) > 4 else ''}")
        if key[0] == "bond":
            lines.append(f"bond   {key[1]:<3s} {key[2]:<3s}          "
                         f"{_mean(values):9.5f} {_mean(forces):11.1f}   {comment}")
        else:
            lines.append(f"angle  {key[1]:<3s} {key[2]:<3s} {key[3]:<3s} {key[4]:<5s} "
                         f"{_mean(values):9.2f} {_mean(forces):11.1f}   {comment}")
    path.write_text("\n".join(lines) + "\n")
    return len(per_key)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--batch", type=Path, nargs="+", required=True)
    parser.add_argument("--record", type=Path, default=DEFAULT_RECORD)
    parser.add_argument("--par", type=Path, default=DEFAULT_QM_BONDED)
    args = parser.parse_args()
    record = (json.loads(args.record.read_text()) if args.record.is_file()
              else {"molecules": {}})
    added = 0
    for batch in args.batch:
        for directory in sorted(p for p in batch.iterdir() if p.is_dir()):
            entry = _collect(directory)
            if entry is not None:
                record["molecules"][directory.name] = entry
                added += 1
    record["molecules"] = dict(sorted(record["molecules"].items()))
    args.record.write_text(json.dumps(record, indent=1) + "\n")
    keys = _write_par(args.par, record)
    print(f"{added} molecules recorded from {len(args.batch)} batch(es); "
          f"{len(record['molecules'])} in the record; {keys} terms in {args.par}")


if __name__ == "__main__":
    main()
    from opls_ff_gen.datafiles import write_manifest  # keep data/MANIFEST.json current

    write_manifest()
